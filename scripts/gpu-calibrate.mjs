// 显卡自适应校准：把 scripts/gpu-measure.sh 的实测输出算成「本地屏浏览器能同时硬解几路」等上限，写进 .env 自动块（2026-11-09）。
//
// 为什么：本地屏要不要让浏览器用显卡原生解 H.265、同时解几路，取决于这块显卡的解码引擎总量；
//   H2Z-66DC（AMD Raven）实测一路 640x360 约占解码引擎 5.6%，总量约 17～18 路；别的显卡（Intel / 新 AMD / 以后的板子）不一样，不能写死。
//   详见 docs/VIDEO-DECODE-STRATEGY-2026-11-09.md §5。
//
// 规则（改系数在这里改，测试会跟着校验）：
//   每路占用 = 合计占用 ÷ 路数，再按像素折算到 640x360（折算系数限制在 0.25～4）、按帧率折算到 25 帧（0.25～2；样片帧率低会把每路算轻）
//   解码槽位 DECODE_SLOTS = round(100 ÷ 每路占用%)                     （引擎打满时能解几路）
//   浏览器原生硬解上限 NATIVE_MAX = min(槽位 − 2, 16)；不足 1 = 0       （留 2 路余量：翻页新旧解码器交叠、远程观看者的硬转；16 = 负责人定的上限）
//   后端 VAAPI 硬转上限 IOC_VAAPI_MAX = min(编码引擎 90% ÷ 每路编码占用, 解码引擎 50% ÷ 每路转码的解码占用)，至少 1
//                                        （每路占用是 gpu-measure.sh 跑 4 路硬转实测的；量不出来不写，后端用保底值）
//   8 路没能实时跑完（最慢一路 < 0.95 倍速）→ 槽位最多 7；读不到引擎占用 → 槽位按保守值 8
//   测过、驱动支持、但显卡不能硬解 H.265 → NATIVE_MAX = 0（页面不再让浏览器软解 H.265，改走转码流）
//   没测成（没有 /dev/dri、NVIDIA / 不认识的驱动、没有样片）→ 只记指纹和原因，不写上限，页面用自己的缺省（不乱下结论）
//
// 覆盖：.env 里「自动块」外面已经有的键，不动、不写（现场手工指定的优先）；自动块每次重算。
// 没验证：NVIDIA（NVDEC 引擎计数器不同，也没有 VAAPI）；Intel 的 i915 引擎名 drm-engine-video 是按文档写的，没在 Intel 机器上实测。
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const NATIVE_CAP = 16;
export const HEADROOM = 2;
export const REF_PIXELS = 640 * 360;
export const REF_FPS = 25;
export const MIN_SPEED = 0.95;
export const CONSERVATIVE_SLOTS = 8;
// 后端显卡转码上限：按这台机器实测的「每路转码占编码引擎 / 解码引擎多少」算，不写死路数（2026-11-10 负责人要求）。
//   编码引擎：只有转码在用，用到 ENC_USABLE（90%）为止；
//   解码引擎：要和浏览器原生硬解共用，转码最多用 DEC_SHARE（一半）——H2Z-66DC 实测浏览器 16 路硬解占解码引擎 23%～44%；
//   两个取小的。量不出来（编不了 / 没跑成）就不写这个键，后端用自己的保底值。
// 这两个是「比例」，不是路数：换一块显卡，量出来的每路占用不同，算出来的路数就不同。
export const ENC_USABLE = 0.9;
export const DEC_SHARE = 0.5;

const BEGIN = '# >>> h2z auto: gpu calibration (regenerated by scripts/gpu-calibrate.sh; to override a key, set it above this block) >>>';
const END = '# <<< h2z gpu <<<';
const KEYS = ['H2Z_GPU_FINGERPRINT', 'H2Z_GPU_VENDOR', 'H2Z_GPU_NODE', 'H2Z_GPU_DECODE_SLOTS', 'H2Z_GPU_NATIVE_MAX', 'IOC_VAAPI_MAX'];
const VENDORS = { '0x1002': 'amd', '0x8086': 'intel', '0x10de': 'nvidia' };

export function parseKv(text) {
  const kv = {};
  for (const line of String(text || '').split(/\r?\n/)) { const m = /^([a-z0-9_]+)=(.*)$/.exec(line); if (m) kv[m[1]] = m[2].trim(); }
  return kv;
}

/** 实测的每路转码占用 → 显卡转码最多几路；没量到 → null */
export function vaapiCap(kv) {
  if (kv.t4_alive !== '4' || !(Number(kv.t4_speed) >= MIN_SPEED)) return null;
  const [w, h] = String(kv.clip_wh || '').split('x').map(Number);
  const scale = w > 0 && h > 0 ? Math.min(4, Math.max(0.25, (w * h) / REF_PIXELS)) : 1;
  const fps = Number(kv.clip_fps);
  const fpsScale = fps > 0 ? Math.min(2, Math.max(0.25, fps / REF_FPS)) : 1;
  const per = (v) => Number(v) / 4 / scale / fpsScale;
  const enc = per(kv.t4_enc_pct), dec = per(kv.t4_dec_pct);
  if (!(enc > 0) && !(dec > 0)) return null;
  const byEnc = enc > 0 ? (100 * ENC_USABLE) / enc : Infinity;
  const byDec = dec > 0 ? (100 * DEC_SHARE) / dec : Infinity;
  return Math.max(1, Math.floor(Math.min(byEnc, byDec)));
}

/** @returns { known: boolean, vendor, node, slots?, nativeMax?, vaapiMax?, costPct?, reason } */
export function calibrate(kv) {
  const vendor = VENDORS[String(kv.vendor_id || '').toLowerCase()] || '';
  const node = kv.node || '';
  const base = { vendor, node };
  const driverKnown = kv.driver === 'amdgpu' || kv.driver === 'i915';
  if (kv.ok !== '1') {
    // 驱动认识、引擎计数器也选好了、却不能硬解 H.265：这是测出来的结论
    if (driverKnown && kv.engine && /不能硬解/.test(kv.reason || '')) return { ...base, known: true, slots: 0, nativeMax: 0, vaapiMax: null, reason: kv.reason };
    return { ...base, known: false, reason: kv.reason || '没测成' };
  }
  const useK8 = kv.k8_pct !== undefined && Number(kv.k8_speed) >= MIN_SPEED && kv.k8_alive === '8';
  const k = useK8 ? 8 : 4;
  const pct = Number(useK8 ? kv.k8_pct : kv.k4_pct);
  let slots;
  let costPct = null;
  let reason;
  if (!(pct > 0)) {
    slots = CONSERVATIVE_SLOTS;
    reason = '读不到解码引擎占用，按保守值 ' + CONSERVATIVE_SLOTS + ' 路';
  } else {
    const [w, h] = String(kv.clip_wh || '').split('x').map(Number);
    const scale = w > 0 && h > 0 ? Math.min(4, Math.max(0.25, (w * h) / REF_PIXELS)) : 1;
    const fps = Number(kv.clip_fps);
    const fpsScale = fps > 0 ? Math.min(2, Math.max(0.25, fps / REF_FPS)) : 1;
    costPct = pct / k / scale / fpsScale;
    slots = Math.max(1, Math.round(100 / costPct));
    if (!useK8) slots = Math.min(slots, 7);
    reason = `${k} 路合计占解码引擎 ${pct}%，折合每路（640x360）${costPct.toFixed(2)}%${useK8 ? '' : '；8 路没能实时跑完，槽位最多 7'}`;
  }
  const nativeMax = Math.max(0, Math.min(NATIVE_CAP, slots - HEADROOM));
  return { ...base, known: true, slots, nativeMax, vaapiMax: vaapiCap(kv), costPct, reason };
}

const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const stripBlock = (text) => text.replace(new RegExp(esc(BEGIN) + '[\\s\\S]*?' + esc(END) + '\\n?'), '');
const hasKey = (text, k) => new RegExp('^' + k + '=\\s*\\S', 'm').test(text);

/** 指纹匹配 = 这台机器的显卡 / 内核 / 镜像没变，沿用上次结果（自动块里有同样的指纹） */
export const fingerprintMatches = (envText, fp) => !!fp && new RegExp('^H2Z_GPU_FINGERPRINT=' + esc(fp) + '\\s*$', 'm').test(String(envText));

export function applyCalibration(envText, result, fingerprint) {
  const base = stripBlock(String(envText)).replace(/\s+$/, '');
  const v = { H2Z_GPU_FINGERPRINT: fingerprint || '', H2Z_GPU_VENDOR: result.vendor || '', H2Z_GPU_NODE: result.node || '' };
  if (result.known) { v.H2Z_GPU_DECODE_SLOTS = String(result.slots); v.H2Z_GPU_NATIVE_MAX = String(result.nativeMax); if (result.vaapiMax != null) v.IOC_VAAPI_MAX = String(result.vaapiMax); }
  const lines = KEYS.filter((k) => v[k] !== undefined && v[k] !== '' && !hasKey(base, k)).map((k) => k + '=' + v[k]);
  if (!lines.length) return base + '\n';
  return base + '\n' + BEGIN + '\n' + lines.join('\n') + '\n' + END + '\n';
}

/** 命令行：node scripts/gpu-calibrate.mjs <.env 路径> <gpu-measure.sh 输出文件> <指纹> */
export function main(envPath, measurePath, fingerprint) {
  if (!existsSync(envPath) || !existsSync(measurePath)) { console.log('缺 ' + (existsSync(envPath) ? measurePath : envPath) + '，跳过'); return false; }
  const r = calibrate(parseKv(readFileSync(measurePath, 'utf8')));
  const old = readFileSync(envPath, 'utf8');
  const next = applyCalibration(old, r, fingerprint);
  if (next !== old) writeFileSync(envPath, next, { mode: 0o600 });
  console.log(r.known
    ? `显卡校准：${r.vendor || '?'} ${r.node}，${r.reason} → 解码槽位 ${r.slots}，浏览器原生硬解上限 ${r.nativeMax}，后端硬转上限 ${r.vaapiMax ?? '没量到（后端用保底值）'}${next === old ? '（无变化）' : '（已写入 ' + envPath + '）'}`
    : `显卡校准：没得出结论（${r.reason}），不写上限，页面用缺省`);
  return next !== old;
}
if (process.argv[1] === fileURLToPath(import.meta.url)) main(process.argv[2] || '.env', process.argv[3] || '/tmp/gpu-measure.out', process.argv[4] || '');
