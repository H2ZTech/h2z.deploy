// 转码内存预算：按整机内存算出 ZLM 容器内存上限和后端的转码路数上限，写进 .env（2026-11-05）。
//
// 为什么：转码的 ffmpeg 跑在 ZLM 容器里，每路约 48 MB 私有内存（dmesg 实测 anon-rss 47～49 MB）。
// 原来写死 1536m（按 16 路设计）；32 分屏全部转码时内核先杀 ffmpeg、再杀 MediaServer，ZLM 反复重启，所有画面一起丢。
// 不同硬件内存不同，不能写死一个数；而且 ZLM 的内存和后端的路数上限必须一致，否则后端放进来的路数 ZLM 装不下。
//
// 规则（改系数在这里改，测试会跟着校验）：
//   预算   = 整机内存 × 45%，最低 1536 MB，最高 8192 MB，向下取整到 64 MB
//   总路数 = (预算 − 512 MB) ÷ 48 MB          （512 MB 留给 ZLM 自己和缓冲）
//   CPU 路数 = 逻辑线程数 × 60% ÷ 0.19        （只对软件转码；0.19 线程/路是 2026-11-09 在 H2Z-66DC 上 transcode-probe 实测，见下）
//   普通转码上限 IOC_TRANSCODE_MAX       = min(总路数, CPU 路数, 软件 64 / 硬件(rkmpp) 64)
//   缩略档上限   IOC_TRANSCODE_THUMB_MAX = max(16, 总路数 − 8)   （留 8 路给回放等普通转码）
//
// 覆盖：.env 里「自动块」外面已经有的键，不动、不写（现场手工指定的优先）；自动块每次重算。
// CPU 项（2026-11-09）：原来只看内存，4C/8T、5.9 GB 的机器内存算出 64 路，32 路软件转码就把 CPU 吃满，ffmpeg 超时重启越转越忙。
//   每路 0.19 线程：transcode-probe 在 H2Z-66DC（Ryzen Embedded R2544，8 线程）上实测，32 路软件转码 640x360 H.265 每秒转 41.7 路、CPU 97%
//   → 8 × 0.97 ÷ 41.7 ≈ 0.19（其中只解码约 0.08）。用的是合成测试片、一台机器，别的 CPU 要各自量。留 40% 给录像、后端、浏览器解码。
//   硬件转码（rkmpp）不套这一项；VAAPI 是否启用要开机后才知道，预算先按软件算（偏保守），启用后用户可在 .env 手工调大。
//   缩略档（只解关键帧）每路便宜得多，不套这一项。不传线程数 = 不算 CPU 项。
// 没验证：RK3588 硬件转码（ffmpeg-rockchip）每路内存，按软件的值保守估；硬件缺省 60 路是否合适要在板子上实测。
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const PER_STREAM_MB = 48;
export const ZLM_BASE_MB = 512;
export const BUDGET_FRACTION = 0.45;
export const BUDGET_MIN_MB = 1536;
export const BUDGET_MAX_MB = 8192;
// 2026-11-05：负责人定「64 路是普通转码上限，128 路才用缩略档」，所以软件、硬件都以 64 为上限（64 分屏每格都要一路转码）
export const FULL_CAP = { soft: 64, hw: 64 };
export const CPU_PER_STREAM = 0.19;
export const CPU_USABLE = 0.6;
export const PLAYBACK_RESERVE = 8;
export const THUMB_MIN = 16;

const BEGIN = '# >>> h2z auto: transcode budget (regenerated by scripts/transcode-budget.mjs; to override a key, set it above this block) >>>';
const END = '# <<< h2z auto <<<';

/** @param totalMB 整机内存（MB） @param opts { hw: 是否 rkmpp 硬件转码, threads: 逻辑线程数（不传 = 不算 CPU 项） } */
export function transcodeBudget(totalMB, { hw = false, threads = 0 } = {}) {
  const total = Number(totalMB);
  const raw = Number.isFinite(total) && total > 0 ? total * BUDGET_FRACTION : BUDGET_MIN_MB;
  const budgetMB = Math.floor(Math.min(BUDGET_MAX_MB, Math.max(BUDGET_MIN_MB, raw)) / 64) * 64;
  const streams = Math.max(1, Math.floor((budgetMB - ZLM_BASE_MB) / PER_STREAM_MB));
  const t = Number(threads);
  const cpuStreams = !hw && Number.isFinite(t) && t > 0 ? Math.max(1, Math.floor((t * CPU_USABLE) / CPU_PER_STREAM)) : Infinity;
  const maxFull = Math.max(1, Math.min(streams, cpuStreams, hw ? FULL_CAP.hw : FULL_CAP.soft));
  const maxThumb = Math.max(THUMB_MIN, streams - PLAYBACK_RESERVE);
  return { budgetMB, streams, cpuStreams: Number.isFinite(cpuStreams) ? cpuStreams : null, ZLM_MEM_LIMIT: budgetMB + 'm', IOC_TRANSCODE_MAX: String(maxFull), IOC_TRANSCODE_THUMB_MAX: String(maxThumb) };
}

const KEYS = ['ZLM_MEM_LIMIT', 'IOC_TRANSCODE_MAX', 'IOC_TRANSCODE_THUMB_MAX'];
const stripBlock = (text) => text.replace(new RegExp(BEGIN.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '[\\s\\S]*?' + END.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '\\n?'), '');
const hasKey = (text, k) => new RegExp('^' + k + '=\\s*\\S', 'm').test(text);

/** 返回新的 .env 文本：手工指定的键保留，其余键写进自动块（块放在文件末尾） */
export function applyBudget(envText, totalMB, opts) {
  const base = stripBlock(String(envText)).replace(/\s+$/, '');
  const b = transcodeBudget(totalMB, opts);
  const lines = KEYS.filter((k) => !hasKey(base, k)).map((k) => k + '=' + b[k]);
  if (!lines.length) return base + '\n';
  return base + '\n' + BEGIN + '\n' + lines.join('\n') + '\n' + END + '\n';
}

export function readTotalMB(meminfo = '/proc/meminfo') {
  try { const m = readFileSync(meminfo, 'utf8').match(/^MemTotal:\s+(\d+)\s*kB/m); return m ? Math.floor(Number(m[1]) / 1024) : 0; } catch { return 0; }
}
export function readThreads(cpuinfo = '/proc/cpuinfo') {
  try { return (readFileSync(cpuinfo, 'utf8').match(/^processor\s*:/gm) || []).length; } catch { return 0; }
}
export const isHw = (envText) => /^COMPOSE_FILE=.*zlm-rk3588/m.test(envText) || /^IOC_TRANSCODE_HW=rkmpp/m.test(envText);

/** 命令行：node scripts/transcode-budget.mjs [.env 路径]；读不到内存就什么也不改 */
export function main(envPath = '.env') {
  if (!existsSync(envPath)) { console.log('没有 ' + envPath + '，跳过'); return false; }
  const mb = readTotalMB();
  if (!mb) { console.log('读不到整机内存，转码预算保持原样'); return false; }
  const old = readFileSync(envPath, 'utf8');
  const opts = { hw: isHw(old), threads: readThreads() };
  const next = applyBudget(old, mb, opts);
  const b = transcodeBudget(mb, opts);
  if (next !== old) writeFileSync(envPath, next, { mode: 0o600 });
  console.log(`整机内存 ${mb} MB、${opts.threads} 线程 → ZLM ${b.ZLM_MEM_LIMIT}，普通转码 ${b.IOC_TRANSCODE_MAX} 路，缩略档 ${b.IOC_TRANSCODE_THUMB_MAX} 路${next === old ? '（无变化）' : '（已写入 ' + envPath + '）'}`);
  return next !== old;
}
if (process.argv[1] === fileURLToPath(import.meta.url)) main(process.argv[2] || '.env');
